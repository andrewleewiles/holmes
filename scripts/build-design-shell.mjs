// Compiles the design shell into the vendored Graphite bundle.
//
// Same reasoning as build-office-shell.mjs: the shell cannot go through
// electron-vite, because the renderer is served from file:// and this page
// has to be served from holmes-design:// so it is same-origin with the
// editor iframe it drives. So it is its own esbuild bundle, written next to
// the editor it wraps.
//
//   node scripts/build-design-shell.mjs      (pnpm build:design-shell)
//
// There is no worker entry point here — Graphite's own wasm worker wiring is
// inside its vite build — so the esbuild worker-URL gotcha (office PATCHES.md
// #1) does not apply. Do not re-add a worker entry without re-reading that note.
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import * as esbuild from 'esbuild'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')

// The version directory is the pinned commit's short hash — read it from the
// protocol module so the two cannot drift.
const protocolSource = fs.readFileSync(path.join(root, 'src/main/designProtocol.ts'), 'utf8')
const commit = /GRAPHITE_COMMIT = '([0-9a-f]{40})'/.exec(protocolSource)?.[1]
if (!commit) {
  console.error('GRAPHITE_COMMIT not found in src/main/designProtocol.ts')
  process.exit(1)
}

const bundleRoot = path.join(root, 'node_modules/.holmes/design/graphite', commit.slice(0, 8))
if (!fs.existsSync(path.join(bundleRoot, 'index.html'))) {
  console.error(`Graphite bundle not found at ${path.relative(root, bundleRoot)}`)
  console.error('Run `pnpm vendor:design` first.')
  process.exit(1)
}
const outDir = path.join(bundleRoot, 'holmes')
fs.mkdirSync(outDir, { recursive: true })

/**
 * Font Awesome Pro icons over Graphite's own, where an equivalent exists.
 *
 * Pro is COMMERCIALLY LICENSED and must not be redistributed, so none of it
 * lives in this repo: the tracked side is a name→name map, and the glyph data
 * is read at build time from a licensed copy on the machine doing the build
 * (`HOLMES_FA_PRO_DIR`, or one of the known local paths). Output lands only in
 * the gitignored bundle. With no pack present the build says so and Graphite
 * keeps its own icons, so a clone without a Pro license still builds.
 */
function findFontAwesomePro() {
  // An explicit override is the whole answer when set: silently falling back
  // to some other copy would hide the fact that the named one is wrong.
  const override = process.env['HOLMES_FA_PRO_DIR']
  const candidates = override
    ? [override]
    : ['/Volumes/andrews-ssd/websites/palimpagosWebsite/infra/lore/web/public/fa']
  for (const dir of candidates) {
    const css = path.join(dir, 'css/fontawesome.css')
    const font = path.join(dir, 'webfonts/fa-solid-900.woff2')
    if (fs.existsSync(css) && fs.existsSync(font)) {
      // The free edition ships the same file names; only Pro carries the icons
      // the map depends on, so check the banner rather than assume.
      if (!/Font Awesome Pro/.test(fs.readFileSync(css, 'utf8').slice(0, 400))) continue
      return { dir, css, font }
    }
  }
  return null
}

/** Every `.fa-name` in the stylesheet → its raw `--fa` content value. */
function readFontAwesomeGlyphs(cssPath) {
  const css = fs.readFileSync(cssPath, 'utf8')
  const glyphs = new Map()
  // Names are comma-separated alias lists, and the value is either a hex
  // escape ("\f0c5 ") or an escaped literal ("\+"), so it is copied verbatim.
  for (const rule of css.matchAll(/([^{}]+)\{--fa:"((?:\\.|[^"\\])*)"/g)) {
    for (const name of rule[1].matchAll(/\.fa-([a-z0-9-]+)/g)) {
      if (!glyphs.has(name[1])) glyphs.set(name[1], rule[2])
    }
  }
  return glyphs
}

let faGenerated = false
const faPro = findFontAwesomePro()
if (!faPro) {
  console.log("  Font Awesome Pro not found — keeping Graphite's own icons.")
  console.log('  (set HOLMES_FA_PRO_DIR to a licensed copy containing css/ and webfonts/)')
} else {
  const glyphs = readFontAwesomeGlyphs(faPro.css)
  const map = JSON.parse(fs.readFileSync(path.join(root, 'src/design-shell/fa-icon-map.json'), 'utf8'))
  const rules = []
  const missing = []
  for (const [graphiteIcon, faName] of Object.entries(map)) {
    const glyph = glyphs.get(faName)
    if (!glyph) { missing.push(`${graphiteIcon} → ${faName}`); continue }
    // The patched IconLabel puts the icon's name in a class (see PATCHES.md);
    // its inline SVG is hidden and the glyph takes its place.
    rules.push(
      `.icon-label.holmes-icon-${graphiteIcon} > svg { display: none; }\n` +
      `.icon-label.holmes-icon-${graphiteIcon}::before { content: "${glyph}"; }`,
    )
  }
  if (missing.length) {
    console.log(`  ${missing.length} mapped name(s) missing from this Pro build: ${missing.join(', ')}`)
  }
  fs.copyFileSync(faPro.font, path.join(outDir, 'fa-solid-900.woff2'))
  const css = `/* Generated by scripts/build-design-shell.mjs from a licensed Font Awesome Pro
   copy at build time. Not redistributable — this file lives only in the
   gitignored bundle. Graphite icon names come from src/design-shell/fa-icon-map.json. */
@font-face {
  font-family: "Holmes FA";
  src: url("./fa-solid-900.woff2") format("woff2");
  font-weight: 900;
  font-style: normal;
  font-display: block;
}
.icon-label[class*="holmes-icon-"]::before {
  font-family: "Holmes FA";
  font-weight: 900;
  font-style: normal;
  line-height: 1;
  /* The glyph replaces an SVG that filled the box, so it is centred in the
     same flex row and coloured by the same variable IconLabel fills with. */
  display: flex;
  align-items: center;
  justify-content: center;
  width: 100%;
  height: 100%;
  color: var(--color-e-nearwhite);
  -webkit-font-smoothing: antialiased;
}
/* Graphite recolours icons per state by overriding \`fill\`, which paints an
   SVG but not a glyph — so each of those states is mirrored here in \`color\`.
   A state missed here costs contrast on one icon, never a missing icon. */
.icon-label.disabled[class*="holmes-icon-"]::before,
.disabled .icon-label[class*="holmes-icon-"]::before { color: var(--color-8-uppergray); }
/* Inverted: these all sit on a light background when active. */
.active > .icon-label[class*="holmes-icon-"]::before,
.active .icon-label[class*="holmes-icon-"]::before,
.emphasized .icon-label[class*="holmes-icon-"]::before,
.checkbox-box .icon-label[class*="holmes-icon-"]::before { color: var(--color-2-mildblack); }
/* Optical sizing: a glyph's cap height sits inside its em box, so matching the
   box pixel-for-pixel renders smaller than the SVG it replaced. */
.icon-label.size-12[class*="holmes-icon-"]::before { font-size: 11px; }
.icon-label.size-16[class*="holmes-icon-"]::before { font-size: 14px; }
.icon-label.size-24[class*="holmes-icon-"]::before { font-size: 20px; }

${rules.join('\n')}
`
  fs.writeFileSync(path.join(outDir, 'fa-icons.css'), css)
  faGenerated = true
  console.log(`  Font Awesome Pro: ${rules.length} icons mapped from ${path.relative(root, faPro.dir) || faPro.dir}`)
}

const result = await esbuild.build({
  entryPoints: [path.join(root, 'src/design-shell/graphite.ts')],
  bundle: true,
  format: 'esm',
  // The frame is Chromium of a known version — no need to down-level.
  target: 'chrome120',
  outfile: path.join(outDir, 'shell.js'),
  // The shell only links the generated stylesheet when this build produced it.
  define: { __HOLMES_FA_ICONS__: String(faGenerated) },
  sourcemap: false,
  minify: true,
  logLevel: 'warning',
  metafile: true,
})

// The shell page itself. Kept here rather than as a file to copy so the
// markup and the script that fills it cannot drift apart.
const html = `<!DOCTYPE html>
<html><head><meta charset="utf-8"><title>Holmes design editor</title>
<style>
  html, body { margin: 0; height: 100%; background: #20201e; overflow: hidden; }
  #holmes-design-root { position: absolute; inset: 0; }
  #holmes-design-root iframe { border: 0; width: 100%; height: 100%; }
</style></head>
<body><div id="holmes-design-root"></div>
<script type="module" src="./shell.js"></script>
</body></html>
`
fs.writeFileSync(path.join(outDir, 'shell.html'), html)

// AppleDouble twins break codesign, and this volume creates one per file.
for (const name of fs.readdirSync(outDir)) {
  if (name.startsWith('._')) fs.rmSync(path.join(outDir, name), { force: true })
}

for (const [file, out] of Object.entries(result.metafile.outputs)) {
  console.log(`  ${path.relative(root, file).padEnd(70)} ${(out.bytes / 1024).toFixed(0)} KB`)
}
